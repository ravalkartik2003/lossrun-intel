#!/usr/bin/env python3
"""Brief 27 Answers 4: the playbook lives in two places from one source.

The command files in .cursor/commands/*.md are the source (Cursor runs them as slash commands). This script writes the
same files to docs/operations/playbook/ for assistants and readers that do not use Cursor, each with a one-line header
saying where to edit. CI runs --check so the two cannot diverge.

    python tools/playbook-sync.py --write    # regenerate docs/operations/playbook/
    python tools/playbook-sync.py --check    # exit 1 and list the files that differ
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / ".cursor" / "commands"
TARGET = ROOT / "docs" / "operations" / "playbook"
HEADER = "<!-- Generated by tools/playbook-sync.py from .cursor/commands/{name}: edit that file, then run `python tools/playbook-sync.py --write`. -->\n\n"


def expected() -> dict:
    files = {}
    for src in sorted(SOURCE.glob("*.md")):
        text = src.read_text(encoding="utf-8").replace("\r\n", "\n")
        files[src.name] = HEADER.format(name=src.name) + text
    return files


def main(argv: list) -> int:
    mode = argv[1] if len(argv) > 1 else "--check"
    want = expected()
    if not want:
        print("playbook-sync: no command files in .cursor/commands/")
        return 1
    if mode == "--write":
        TARGET.mkdir(parents=True, exist_ok=True)
        for stale in TARGET.glob("*.md"):
            if stale.name not in want:
                stale.unlink()
        for name, text in want.items():
            (TARGET / name).write_text(text, encoding="utf-8", newline="\n")
        print(f"playbook-sync: wrote {len(want)} file(s) to docs/operations/playbook/")
        return 0
    differ = []
    for name, text in want.items():
        path = TARGET / name
        if not path.exists() or path.read_text(encoding="utf-8").replace("\r\n", "\n") != text:
            differ.append(name)
    extra = [p.name for p in TARGET.glob("*.md") if p.name not in want] if TARGET.exists() else []
    if differ or extra:
        print("playbook-sync: docs/operations/playbook/ differs from .cursor/commands/: " + ", ".join(differ + extra))
        print("run: python tools/playbook-sync.py --write")
        return 1
    print(f"playbook-sync: {len(want)} file(s) in step")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
