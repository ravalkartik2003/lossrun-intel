using System.Diagnostics;
using System.Globalization;
using System.Text;
using Microsoft.Data.SqlClient;

namespace LossRun.DbDeploy;

/// <summary>What deploy would do (or did) with one changeset.</summary>
public sealed record PlanStep(Changeset Changeset, string Action, string? Detail = null);

/// <summary>
/// The POC runner of ADR 0006: applies changesets in order, each in its own transaction together with its
/// dbo.SchemaChangeLog row; skips applied ones; refuses checksum drift unless runOnChange. Entra token auth comes
/// from the connection string (Authentication=Active Directory Default).
/// </summary>
public sealed class Deployer(string connectionString, IReadOnlyList<Changeset> changesets, IReadOnlyDictionary<string, string> parameters, Action<string>? log = null)
{
    private readonly Action<string> _log = log ?? Console.WriteLine;

    public async Task<IReadOnlyList<PlanStep>> PlanAsync(CancellationToken cancellationToken = default)
    {
        await using var connection = await LossRun.Data.SqlConnections.OpenAsync(connectionString, cancellationToken).ConfigureAwait(false);
        var applied = await AppliedAsync(connection, cancellationToken).ConfigureAwait(false);
        return [.. changesets.Select(c => Step(c, applied))];
    }

    /// <summary>Applies pending changesets; returns the steps taken. Throws on drift (nothing after the drifted changeset runs).</summary>
    public async Task<IReadOnlyList<PlanStep>> DeployAsync(CancellationToken cancellationToken = default)
    {
        await using var connection = await LossRun.Data.SqlConnections.OpenAsync(connectionString, cancellationToken).ConfigureAwait(false);
        await EnsureLogAsync(connection, cancellationToken).ConfigureAwait(false);
        var applied = await AppliedAsync(connection, cancellationToken).ConfigureAwait(false);
        var steps = new List<PlanStep>();
        var order = applied.Count == 0 ? 0 : applied.Values.Max(a => a.Order);
        foreach (var changeset in changesets)
        {
            var step = Step(changeset, applied);
            if (step.Action == "drift")
            {
                throw new InvalidOperationException($"Checksum drift on {changeset.Key} ({changeset.File}): {step.Detail}. Add a new changeset, or mark it runOnChange:true.");
            }

            if (step.Action == "skip")
            {
                steps.Add(step);
                continue;
            }

            var watch = Stopwatch.StartNew();
            await using var tx = (SqlTransaction)await connection.BeginTransactionAsync(cancellationToken).ConfigureAwait(false);
            await using (var command = new SqlCommand(changeset.Render(parameters), connection, tx) { CommandTimeout = 300 })
            {
                await command.ExecuteNonQueryAsync(cancellationToken).ConfigureAwait(false);
            }

            await using (var record = new SqlCommand(step.Action == "apply"
                ? "INSERT INTO dbo.SchemaChangeLog (Id, Author, FileName, OrderExecuted, ExecType, MD5Sum, Description, Comments) VALUES (@id, @author, @file, @order, N'EXECUTED', @sum, N'sql', @comment)"
                : "UPDATE dbo.SchemaChangeLog SET MD5Sum = @sum, DateExecuted = sysutcdatetime(), ExecType = N'RERAN' WHERE Id = @id AND Author = @author AND FileName = @file",
                connection, tx))
            {
                record.Parameters.AddWithValue("@id", changeset.Id);
                record.Parameters.AddWithValue("@author", changeset.Author);
                record.Parameters.AddWithValue("@file", changeset.File);
                record.Parameters.AddWithValue("@order", ++order);
                record.Parameters.AddWithValue("@sum", changeset.Checksum);
                record.Parameters.AddWithValue("@comment", (object?)Clip(changeset.Comment) ?? DBNull.Value);
                await record.ExecuteNonQueryAsync(cancellationToken).ConfigureAwait(false);
            }

            await tx.CommitAsync(cancellationToken).ConfigureAwait(false);
            _log($"  {step.Action,-7} {changeset.Key} ({watch.ElapsedMilliseconds} ms)");
            steps.Add(step);
        }

        return steps;
    }

    /// <summary>Concatenated script for sqlcmd: each changeset guarded by its SchemaChangeLog row, parameters as sqlcmd :setvar variables.</summary>
    public static string Script(IReadOnlyList<Changeset> changesets, IReadOnlyDictionary<string, string> defaults)
    {
        var sb = new StringBuilder("-- Generated by lossrun-db emit from db/master.xml. Run with sqlcmd -i deploy.sql (-v name=value overrides the parameters).\n");
        foreach (var (name, value) in defaults.OrderBy(d => d.Key, StringComparer.Ordinal))
        {
            sb.AppendLine(CultureInfo.InvariantCulture, $":setvar {name} \"{value}\"");
        }

        sb.AppendLine("SET XACT_ABORT ON;\nGO");
        var order = 0;
        foreach (var c in changesets)
        {
            var sql = System.Text.RegularExpressions.Regex.Replace(c.Body, @"\$\{([A-Za-z0-9_.]+)\}", "$($1)");
            var guard = $"N'{c.Id}' AND Author = N'{c.Author}' AND FileName = N'{c.File}'";
            sb.AppendLine(CultureInfo.InvariantCulture, $"\n-- changeset {c.Key} ({c.File})");
            sb.AppendLine(CultureInfo.InvariantCulture, $"IF OBJECT_ID(N'dbo.SchemaChangeLog', N'U') IS NULL OR NOT EXISTS (SELECT 1 FROM dbo.SchemaChangeLog WHERE Id = {guard}){(c.RunOnChange ? $" OR EXISTS (SELECT 1 FROM dbo.SchemaChangeLog WHERE Id = {guard} AND MD5Sum <> N'{c.Checksum}')" : "")}");
            sb.AppendLine("    EXEC (N'" + sql.Replace("'", "''", StringComparison.Ordinal) + "');");
            sb.AppendLine("GO");
            sb.AppendLine(CultureInfo.InvariantCulture,
                $"IF NOT EXISTS (SELECT 1 FROM dbo.SchemaChangeLog WHERE Id = {guard}) INSERT INTO dbo.SchemaChangeLog (Id, Author, FileName, OrderExecuted, ExecType, MD5Sum, Description) VALUES (N'{c.Id}', N'{c.Author}', N'{c.File}', {++order}, N'EXECUTED', N'{c.Checksum}', N'sqlcmd');");
            sb.AppendLine("GO");
        }

        return sb.ToString();
    }

    private PlanStep Step(Changeset c, IReadOnlyDictionary<string, (string Checksum, int Order)> applied)
    {
        if (!applied.TryGetValue(Key(c), out var row))
        {
            return new PlanStep(c, "apply");
        }

        if (c.RunAlways)
        {
            return new PlanStep(c, "rerun", "runAlways");
        }

        if (row.Checksum == c.Checksum)
        {
            return new PlanStep(c, "skip");
        }

        return c.RunOnChange ? new PlanStep(c, "rerun", "changed (runOnChange)") : new PlanStep(c, "drift", $"recorded {row.Checksum[..12]}…, file {c.Checksum[..12]}…");
    }

    private static string Key(Changeset c) => $"{c.Author}|{c.Id}|{c.File}";

    private async Task EnsureLogAsync(SqlConnection connection, CancellationToken cancellationToken)
    {
        // The log table is changeset 0001; it must exist before the first lookup, so the runner creates it from that changeset.
        var bootstrap = changesets.FirstOrDefault(c => c.Body.Contains("CREATE TABLE dbo.SchemaChangeLog", StringComparison.Ordinal))
            ?? throw new InvalidDataException("No changeset creates dbo.SchemaChangeLog.");
        await using var command = new SqlCommand(bootstrap.Render(parameters), connection);
        await command.ExecuteNonQueryAsync(cancellationToken).ConfigureAwait(false);
    }

    private static async Task<Dictionary<string, (string Checksum, int Order)>> AppliedAsync(SqlConnection connection, CancellationToken cancellationToken)
    {
        var result = new Dictionary<string, (string, int)>(StringComparer.Ordinal);
        await using var command = new SqlCommand("IF OBJECT_ID(N'dbo.SchemaChangeLog', N'U') IS NOT NULL SELECT Id, Author, FileName, MD5Sum, OrderExecuted FROM dbo.SchemaChangeLog", connection);
        await using var reader = await command.ExecuteReaderAsync(cancellationToken).ConfigureAwait(false);
        while (await reader.ReadAsync(cancellationToken).ConfigureAwait(false))
        {
            result[$"{reader.GetString(1)}|{reader.GetString(0)}|{reader.GetString(2)}"] = (reader.GetString(3), reader.GetInt32(4));
        }

        return result;
    }

    private static string? Clip(string? text) => text is { Length: > 255 } ? text[..255] : text;
}
