/// <summary>
/// Brief 10 analytics evaluation: golden parity cases for the TypeScript twin (<c>eval golden</c>) and insight accuracy of the
/// feature engine against corpus truth or a client reference set (<c>eval insights</c>).
/// </summary>
public static class AnalyticsEval
{
    // ------------------------------------------------------------------ golden cases

    /// <summary>
    /// Writes ≥ <paramref name="count"/> parity cases: corpus-v2 truth documents as accounts, enriched deterministically with the
    /// fields the corpus does not print (codes, litigation, CT, recoveries, exposures, overrides) so every metric is
    /// exercised, each under a rotating scenario. Expected = the C# snapshot; the twin must reproduce it byte for byte.
    /// </summary>
    public static int Golden(string corpusDir, string outPath, int count, int maxClaims)
    {
        var manifest = CorpusManifest.Load(corpusDir);
        var logical = manifest.Entries.Where(e => e.Layout != "narrative").GroupBy(e => e.LogicalId).Select(g => g.First()).Take(count).ToList();
        var cases = new JsonArray();
        for (var i = 0; i < logical.Count; i++)
        {
            var truth = CorpusManifest.Truth(corpusDir, logical[i].Id);
            var input = Enrich(AccountBuilder.Build($"GOLD-{i:000}", [new AccountDocument(truth.Id, truth.Document, [])]), new Random(1000 + i), maxClaims);
            var scenario = Scenarios(input)[i % Scenarios(input).Count];
            var view = i % 7 == 3 ? AccountBuilder.AsReported : AccountBuilder.AsAdjusted;
            var snapshot = FeatureEngine.Compute(input, scenario, view);
            cases.Add(new JsonObject
            {
                ["name"] = $"{truth.Id}#{i % Scenarios(input).Count}",
                ["view"] = view,
                ["input"] = JsonNode.Parse(AnalyticsJson.WriteInput(input)),
                ["scenario"] = scenario.IsBaseline ? null : JsonNode.Parse(AnalyticsJson.WriteScenario(scenario)),
                ["expected"] = snapshot.ToJson(),
            });
        }

        var root = new JsonObject
        {
            ["description"] = "Golden parity cases (ADR 0011): generated by `lossrun eval golden` from corpus-v2 truth (enriched deterministically); expected = the C# feature snapshot. The TypeScript twin must reproduce each expected string byte for byte.",
            ["catalogVersion"] = Catalog.Embedded.Version,
            ["perfAccountSnapshotSha256"] = Convert.ToHexStringLower(System.Security.Cryptography.SHA256.HashData(Encoding.UTF8.GetBytes(FeatureEngine.Compute(PerfAccount.Build()).ToJson()))),
            ["cases"] = cases,
        };
        File.WriteAllText(outPath, root.ToJsonString(new JsonSerializerOptions { WriteIndented = false }) + "\n");
        Console.WriteLine($"golden: {cases.Count} cases → {outPath}");
        return 0;
    }

    private static IReadOnlyList<Scenario> Scenarios(AnalyticsInput input)
    {
        var years = input.Claims.Select(c => c.PolicyYear).OfType<int>().Distinct().Order().ToList();
        var first = input.Claims.FirstOrDefault()?.Id;
        return
        [
            new Scenario(),
            new Scenario { ReserveFactorBps = 1000 },
            new Scenario { ReserveFactorBps = -2500, CapPerClaimCents = 25_000_000 },
            new Scenario { ExcludeCatastrophicAboveCents = 10_000_000, IncludeNonCA = false },
            new Scenario { IncludeCT = false, TrendFactorBpsByYear = years.Take(2).Select((y, k) => (y, 10_000 + 350 * (k + 1))).ToDictionary(x => x.y, x => x.Item2) },
            new Scenario { ExcludeClaimIds = first is null ? [] : [first], CapPerClaimCents = 5_000_000, ReserveFactorBps = 333 },
        ];
    }

    private static readonly string[] Causes = ["56", "29", "97", "98", "31", "60", "81", "45"];
    private static readonly string[] Parts = ["42", "36", "38", "53", "90", "91", "21"];
    private static readonly string[] Natures = ["52", "40", "60", "78", "10", "83", "49"];
    private static readonly string[] Descriptions = ["lifting box", "Cumulative strain, both wrists", "slip on wet floor", "repetitive keying", "struck by pallet", "CT psych claim"];

    private static AnalyticsInput Enrich(AnalyticsInput input, Random rng, int maxClaims)
    {
        var claims = input.Claims.Take(maxClaims).Select(c => c with
        {
            CauseCode = rng.Next(5) == 0 ? null : Causes[rng.Next(Causes.Length)],
            BodyPartCode = rng.Next(6) == 0 ? null : Parts[rng.Next(Parts.Length)],
            NatureCode = rng.Next(6) == 0 ? null : Natures[rng.Next(Natures.Length)],
            TypeOfLossCode = rng.Next(10) == 0 ? "02" : null,
            Description = rng.Next(3) == 0 ? Descriptions[rng.Next(Descriptions.Length)] : null,
            Litigation = rng.Next(4) == 0 ? null : rng.Next(5) == 0,
            CumulativeTrauma = rng.Next(12) == 0 ? true : null,
            RecoveryCents = rng.Next(9) == 0 ? (c.IndemnityPaidCents + c.MedicalPaidCents) / (rng.Next(2, 6)) : null,
        }).ToList();
        var years = claims.Select(c => c.PolicyYear).OfType<int>().Distinct().Order().ToList();
        var context = input.Context with
        {
            PayrollCentsByYear = rng.Next(3) == 0 ? null : years.ToDictionary(y => y, _ => (long)rng.Next(50, 400) * 1_000_000_00L / 10),
            FteByYear = rng.Next(3) == 0 ? null : years.ToDictionary(y => y, _ => (long)rng.Next(8, 250)),
            LastDayWorked = rng.Next(2) == 0 ? null : claims.Select(c => c.DateOfInjury).OfType<string>().Order(StringComparer.Ordinal).Skip(claims.Count / 2).FirstOrDefault(),
        };
        var overrides = claims.Where(_ => rng.Next(8) == 0).Take(4)
            .Select((c, k) => new OverrideRef($"ov-{k + 1}", c.Id, new[] { "indemnity.reserve", "medical.paid", "status", "dateClosed" }[k % 4])).ToList();
        return new AnalyticsInput(claims, context, overrides);
    }

    // ------------------------------------------------------------------ insight accuracy

    public sealed record MetricScore(string Metric, string Unit, string Tolerance, int Compared, int Within, int BothNull, int NullMismatch, List<string> Misses);

    /// <summary>
    /// Scores the engine on extracted documents against the same metrics computed from truth (brief 10 §5): counts exact,
    /// money within $1 or 0.1 % (the larger), ratios and rates within 1 % relative, days within 0.5. Truth is reduced to the
    /// fields the layout prints, so a difference is an extraction error, not a field the run never shows. Delivered documents
    /// only (Review documents deliver nothing).
    /// </summary>
    /// <param name="source"><c>delivered</c> (the headline) or <c>prefill</c>: Review documents' pre-fill, a control that shows the
    /// comparator catches extraction errors where they exist.</param>
    public static int Insights(string corpusDir, string resultsDir, string outDir, string? referenceCsv, string source = "delivered")
    {
        Directory.CreateDirectory(outDir);
        var catalog = Catalog.Embedded;
        var scores = catalog.Metrics.ToDictionary(m => m.Name, m => new MetricScore(m.Name, m.Unit, Describe(m), 0, 0, 0, 0, []));
        var manifest = CorpusManifest.Load(corpusDir);
        int docs = 0, delivered = 0;
        foreach (var entry in manifest.Entries)
        {
            var path = Path.Combine(resultsDir, "docs", entry.Id + ".json");
            if (!File.Exists(path))
            {
                continue;
            }

            docs++;
            var result = JsonSerializer.Deserialize<RunResult>(File.ReadAllText(path), CanonicalJson.Options)!;
            var truth = CorpusManifest.Truth(corpusDir, entry.Id);
            var predicted = result.Documents.FirstOrDefault(d => d.FirstPage is null || d.FirstPage <= truth.LossRunSegment.EndPage && (d.LastPage ?? int.MaxValue) >= truth.LossRunSegment.StartPage);
            var extracted = source == "prefill"
                ? predicted?.FinalTier == "Review" ? predicted.PreFill ?? predicted.Document : null
                : predicted?.FinalTier == "Review" ? null : predicted?.Document;
            if (extracted is null)
            {
                continue;
            }

            delivered++;
            // Corpus v3: the submission's payroll/FTE context goes to both sides (it is not extracted; the metrics that need it then measure).
            var context = truth.Context is { } c ? new AnalyticsContext(entry.Id, null, c.PayrollCentsByYear, c.FteByYear) : null;
            var expected = FeatureEngine.Compute(AccountBuilder.Build(entry.Id, [new AccountDocument(entry.Id, PrintedOnly(truth), [])], AccountBuilder.AsAdjusted, context));
            var actual = FeatureEngine.Compute(AccountBuilder.Build(entry.Id, [new AccountDocument(entry.Id, extracted, [])], AccountBuilder.AsAdjusted, context));
            foreach (var m in catalog.Metrics)
            {
                Compare(scores, m, entry.Id, expected[m.Name], actual[m.Name]);
            }
        }

        var reference = referenceCsv is null ? null : ScoreReference(referenceCsv, resultsDir, corpusDir);
        var md = new StringBuilder();
        md.AppendLine("# Insight accuracy — feature engine vs truth (ADR 0011)").AppendLine();
        md.AppendLine(CultureInfo.InvariantCulture, $"Catalog `{catalog.Version}` · results `{Path.GetFileName(Path.TrimEndingDirectorySeparator(resultsDir))}` · {docs} documents, {delivered} {(source == "prefill" ? "Review pre-fills (control)" : "delivered")} scored · truth reduced to printed fields.").AppendLine();
        md.AppendLine("Tolerances: counts exact; money within $1 or 0.1 % (the larger); ratios and rates within 1 % relative; days within 0.5. A metric value and every breakdown entry must be within tolerance. \"Not measurable\" = the corpus prints none of the metric's inputs (both sides null on every document).").AppendLine();
        md.AppendLine("| Metric | Unit | Tolerance | Documents compared | Within tolerance | Rate | Both null | Null on one side | Status |");
        md.AppendLine("|---|---|---|---:|---:|---:|---:|---:|---|");
        foreach (var s in scores.Values)
        {
            var measurable = s.Compared > s.BothNull;
            var rate = s.Compared == 0 ? "—" : $"{100.0 * s.Within / s.Compared:0.0} %";
            var status = !measurable ? "not measurable on this corpus" : s.Within == s.Compared ? "within tolerance" : $"**{s.Compared - s.Within} miss(es)**";
            md.AppendLine(CultureInfo.InvariantCulture, $"| {s.Metric} | {s.Unit} | {s.Tolerance} | {s.Compared} | {s.Within} | {rate} | {s.BothNull} | {s.NullMismatch} | {status} |");
        }

        var misses = scores.Values.Where(s => s.Misses.Count > 0).ToList();
        if (misses.Count > 0)
        {
            md.AppendLine().AppendLine("## Misses (first 5 per metric)").AppendLine();
            foreach (var s in misses)
            {
                md.AppendLine(CultureInfo.InvariantCulture, $"- **{s.Metric}**: {string.Join("; ", s.Misses.Take(5))}");
            }
        }

        if (reference is not null)
        {
            md.AppendLine().AppendLine("## Reference set").AppendLine().Append(reference);
        }

        File.WriteAllText(Path.Combine(outDir, "insights.md"), md.ToString());
        File.WriteAllText(Path.Combine(outDir, "insights.json"), JsonSerializer.Serialize(new { catalog.Version, docs, delivered, scores = scores.Values }, new JsonSerializerOptions(CanonicalJson.Options) { WriteIndented = true }));
        Console.WriteLine($"insights: {delivered}/{docs} delivered documents scored → {outDir}");
        return 0;
    }

    private static string Describe(MetricDef m) => m.Tolerance["kind"]!.GetValue<string>() switch
    {
        "exact" => "exact",
        "money" => "$1 / 0.1 %",
        "relative" => "1 % rel.",
        "absolute" => $"±{m.Tolerance["value"]}",
        var k => k,
    };

    private static void Compare(Dictionary<string, MetricScore> scores, MetricDef m, string doc, MetricResult expected, MetricResult actual)
    {
        var s = scores[m.Name];
        var bothNull = expected.Value is null && actual.Value is null;
        var nullMismatch = (expected.Value is null) != (actual.Value is null);
        var ok = bothNull || !nullMismatch && Within(m, expected.Value!.Value, actual.Value!.Value);
        var e = (expected.Breakdown ?? []).ToDictionary(b => b.Key, b => b.Value);
        var a = (actual.Breakdown ?? []).ToDictionary(b => b.Key, b => b.Value);
        foreach (var key in e.Keys.Union(a.Keys))
        {
            var ev = e.GetValueOrDefault(key);
            var av = a.GetValueOrDefault(key);
            ok &= ev is null && av is null || ev is not null && av is not null && Within(m, ev.Value, av.Value);
        }

        if (!ok && s.Misses.Count < 20)
        {
            s.Misses.Add($"{doc}: truth {Print(m, expected)} vs extracted {Print(m, actual)}");
        }

        scores[m.Name] = s with
        {
            Compared = s.Compared + 1,
            Within = s.Within + (ok ? 1 : 0),
            BothNull = s.BothNull + (bothNull ? 1 : 0),
            NullMismatch = s.NullMismatch + (nullMismatch ? 1 : 0),
        };
    }

    private static string Print(MetricDef m, MetricResult r) => r.Value is { } v ? CanonicalWriter.FormatScaled(v, m.Scale) : "null";

    /// <summary>Whether two values at the metric's scale agree within its catalog tolerance.</summary>
    public static bool Within(MetricDef m, long expected, long actual)
    {
        var diff = Math.Abs((decimal)expected - actual);
        return m.Tolerance["kind"]!.GetValue<string>() switch
        {
            "exact" => diff == 0,
            "money" => diff <= Math.Max(100m, Math.Abs(expected) * 0.001m),
            "relative" => diff <= Math.Max(1m, Math.Abs(expected) * m.Tolerance["value"]!.GetValue<decimal>()),
            "absolute" => diff <= m.Tolerance["value"]!.GetValue<decimal>() * Pow10(m.Scale),
            _ => false,
        };
    }

    private static decimal Pow10(int scale) => scale switch { 0 => 1m, 1 => 10m, 2 => 100m, _ => 1_000_000m };

    /// <summary>The truth document with every claim and period field the layout does not print removed.</summary>
    public static LossRunDocument PrintedOnly(TruthRecord truth)
    {
        var node = JsonSerializer.SerializeToNode(truth.Document, CanonicalJson.Options)!.AsObject();
        var claimFields = truth.Printed.ClaimFields.ToHashSet(StringComparer.Ordinal);
        var periodFields = truth.Printed.PeriodFields.ToHashSet(StringComparer.Ordinal);
        foreach (var period in node["policyPeriods"]!.AsArray().OfType<JsonObject>())
        {
            foreach (var name in new[] { "policyNumber", "effectiveDate", "expirationDate" }.Where(n => !periodFields.Contains(n)))
            {
                period.Remove(name);
            }

            foreach (var claim in period["claims"]!.AsArray().OfType<JsonObject>())
            {
                foreach (var (name, value) in claim.ToList())
                {
                    if (value is JsonObject triplet && name is "indemnity" or "medical" or "expense" or "total")
                    {
                        foreach (var leaf in triplet.Select(kv => kv.Key).ToList().Where(leaf => !claimFields.Contains($"{name}.{leaf}")))
                        {
                            triplet.Remove(leaf);
                        }
                    }
                    else if (!claimFields.Contains(name) && name is not "lineOfBusiness")
                    {
                        claim.Remove(name);
                    }
                }
            }
        }

        return node.Deserialize<LossRunDocument>(CanonicalJson.Options)!;
    }

    // ------------------------------------------------------------------ client reference set

    /// <summary>Header of the reference-set CSV the client's actuaries fill in (docs/analytics/reference-set-template.csv).</summary>
    public const string ReferenceHeader = "account_id,metric,breakdown_key,expected_value,unit,valuation_date,prepared_by,notes";

    /// <summary>
    /// Scores the engine against a filled reference CSV: one row per (account, metric[, breakdown key]); <c>account_id</c> is a
    /// corpus/run document id here, a quote id against the API. Values in the metric's printed unit (dollars, ratio 0–1, days).
    /// </summary>
    public static string ScoreReference(string csvPath, string resultsDir, string corpusDir)
    {
        var lines = File.ReadAllLines(csvPath).Where(l => l.Trim().Length > 0).ToList();
        if (lines.Count == 0 || lines[0].Trim() != ReferenceHeader)
        {
            throw new FormatException($"reference set must start with the header: {ReferenceHeader}");
        }

        var catalog = Catalog.Embedded;
        var snapshots = new Dictionary<string, FeatureSnapshot?>(StringComparer.Ordinal);
        int rows = 0, within = 0, skipped = 0;
        var misses = new List<string>();
        foreach (var line in lines.Skip(1))
        {
            var f = line.Split(',');
            var (account, metric, key, expected) = (f[0].Trim(), f[1].Trim(), f[2].Trim(), f[3].Trim());
            if (!snapshots.TryGetValue(account, out var snapshot))
            {
                var path = Path.Combine(resultsDir, "docs", account + ".json");
                var doc = File.Exists(path) ? JsonSerializer.Deserialize<RunResult>(File.ReadAllText(path), CanonicalJson.Options)!.Documents.FirstOrDefault()?.Document : null;
                snapshots[account] = snapshot = doc is null ? null : FeatureEngine.Compute(AccountBuilder.Build(account, [new AccountDocument(account, doc, [])]));
            }

            if (expected.Length == 0)
            {
                skipped++; // the actuary did not provide this value
                continue;
            }

            rows++;
            var m = catalog[metric];
            var result = snapshot?[metric];
            var actual = key.Length == 0 ? result?.Value : result?.Breakdown?.FirstOrDefault(b => b.Key == key).Value;
            var expectedScaled = (long)Math.Round(decimal.Parse(expected, CultureInfo.InvariantCulture) * Pow10(m.Scale), MidpointRounding.AwayFromZero);
            var ok = actual is not null && Within(m, expectedScaled, actual.Value);
            within += ok ? 1 : 0;
            if (!ok)
            {
                misses.Add($"{account} {metric}{(key.Length > 0 ? $"[{key}]" : "")}: reference {expected} vs engine {(actual is null ? "null" : CanonicalWriter.FormatScaled(actual.Value, m.Scale))}");
            }
        }

        return $"{within}/{rows} reference values within tolerance ({skipped} row(s) left blank, not scored).{(misses.Count > 0 ? "\n\n" + string.Join("\n", misses.Take(20).Select(x => "- " + x)) : "")}\n";
    }
}
